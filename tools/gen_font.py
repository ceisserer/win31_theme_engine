#!/usr/bin/env python3
"""Generates host/font_data.c: a small proportional bitmap font for the host
preview backend, rasterised (no anti-aliasing) from DejaVu Sans.

DejaVu fonts are under the Bitstream Vera licence, which allows embedding.
Usage: tools/gen_font.py [path/to/DejaVuSans.ttf]   (writes host/font_data.[ch])
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
SIZE = 11      # pixel size: close to MS Sans Serif 8 pt at 96 dpi
font = ImageFont.truetype(ttf, SIZE)
ascent, descent = font.getmetrics()
height = ascent + descent

out = []
out.append("/* Generated by tools/gen_font.py from DejaVu Sans (Bitstream Vera licence). Do not edit. */")
out.append('#include "font_data.h"')
out.append("")
glyphs = []
for code in range(32, 127):
    ch = chr(code)
    adv = int(round(font.getlength(ch)))
    w = max(adv, 1)
    img = Image.new("1", (w + 4, height), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((0, 0), ch, font=font, fill=1)
    rows = []
    for y in range(height):
        bits = 0
        for x in range(min(w, 16)):
            if img.getpixel((x, y)):
                bits |= 1 << x
        rows.append(bits)
    glyphs.append((adv, rows))

out.append("const int font_height = %d;" % height)
out.append("const int font_ascent = %d;" % ascent)
out.append("const unsigned char font_advance[95] = {")
out.append("    " + ", ".join(str(a) for a, _ in glyphs))
out.append("};")
out.append("const unsigned short font_rows[95][%d] = {" % height)
for (a, rows), code in zip(glyphs, range(32, 127)):
    out.append("    { %s }, /* %r */" % (", ".join("0x%04x" % r for r in rows), chr(code)))
out.append("};")
import os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "host")
with open(os.path.join(root, "font_data.c"), "w") as f:
    f.write("\n".join(out) + "\n")
with open(os.path.join(root, "font_data.h"), "w") as f:
    f.write("/* font_data.h - embedded preview font (generated by tools/gen_font.py). */\n"
            "#ifndef FONT_DATA_H\n#define FONT_DATA_H\n"
            "#define FONT_HEIGHT %d\n"
            "extern const int font_height;\nextern const int font_ascent;\n"
            "extern const unsigned char font_advance[95];\n"
            "extern const unsigned short font_rows[95][FONT_HEIGHT];\n#endif\n" % height)
